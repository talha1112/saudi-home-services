import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Transform, Type } from 'class-transformer';
import { IsEnum, IsInt, IsOptional, IsString, Matches, Max, MaxLength, Min } from 'class-validator';
import { PageMetaDto, PageQueryDto } from '../../common/pagination/pagination.js';
import { Role, SupportThreadStatus } from '../../generated/prisma/client.js';

const trim = ({ value }: { value: unknown }) => (typeof value === 'string' ? value.trim() : value);

/** Chosen by the app for each message and reused when it retries, so a retry can never create a second message. */
export const CLIENT_MESSAGE_ID_RE = /^[A-Za-z0-9_-]{8,64}$/;

export class SendSupportMessageDto {
  @ApiProperty({ description: 'A unique id generated by the app per message (8-64 chars: letters, digits, _ -). Resend the SAME id when retrying.' })
  @IsString()
  @Matches(CLIENT_MESSAGE_ID_RE)
  clientMessageId!: string;

  @ApiProperty({ description: 'Plain text, 1-2000 characters.' })
  @IsString()
  @MaxLength(8000) // hard bound before the real (character-count) rule in the service
  body!: string;
}

export class AdminReplyDto {
  @ApiProperty({ description: 'Plain text, 1-2000 characters.' })
  @IsString()
  @MaxLength(8000)
  body!: string;

  @ApiPropertyOptional({ description: 'Reuse the same id when retrying so the reply is stored once (8-64 chars).' })
  @IsOptional()
  @Matches(CLIENT_MESSAGE_ID_RE)
  clientMessageId?: string;
}

export class SupportMessagesQueryDto {
  @ApiPropertyOptional({ description: 'Return messages with seq GREATER than this, oldest first (polling / reconnect recovery).' })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(0)
  @Max(2147483647)
  afterSeq?: number;

  @ApiPropertyOptional({ description: 'Return messages with seq LESS than this (scrolling back). Omit both for the latest page.' })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(2147483647)
  beforeSeq?: number;

  @ApiPropertyOptional({ default: 50, minimum: 1, maximum: 200 })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(200)
  limit: number = 50;
}

export class ListSupportThreadsQueryDto extends PageQueryDto {
  @ApiPropertyOptional({ enum: SupportThreadStatus, description: 'Default: every conversation, the ones waiting for an administrator first.' })
  @IsOptional()
  @Transform(({ value }) => (typeof value === 'string' ? value.trim().toUpperCase() : value))
  @IsEnum(SupportThreadStatus)
  status?: SupportThreadStatus;

  @ApiPropertyOptional({ description: 'Part of a name or phone number.' })
  @IsOptional()
  @Transform(trim)
  @IsString()
  @MaxLength(80)
  search?: string;
}

export class SupportMessageDto {
  @ApiProperty() id!: string;
  @ApiProperty() seq!: number;
  @ApiProperty({ enum: Role }) senderRole!: Role;
  @ApiProperty() clientMessageId!: string;
  @ApiProperty() body!: string;
  @ApiProperty() createdAt!: string;
  @ApiProperty({ description: 'Whether the signed-in person wrote it' }) fromMe!: boolean;
}

export class SupportMessagesMetaDto {
  @ApiProperty() limit!: number;
  @ApiProperty() hasMore!: boolean;
  @ApiProperty() lastSeq!: number;
  @ApiProperty({ description: 'Always true for the person: a conversation can always be written to' }) canSend!: boolean;
  @ApiProperty({ enum: SupportThreadStatus, nullable: true }) status!: SupportThreadStatus | null;
}

export class SupportMessagesPageDto {
  @ApiProperty({ type: [SupportMessageDto] }) items!: SupportMessageDto[];
  @ApiProperty({ type: SupportMessagesMetaDto }) meta!: SupportMessagesMetaDto;
}

export class AdminSupportThreadDto {
  @ApiProperty() id!: string;
  @ApiProperty() userId!: string;
  @ApiProperty({ enum: SupportThreadStatus }) status!: SupportThreadStatus;
  @ApiProperty({ enum: Role }) role!: Role;
  @ApiProperty({ nullable: true }) fullName!: string | null;
  @ApiProperty({ nullable: true }) phone!: string | null;
  @ApiProperty({ nullable: true, description: 'For workers: the application status (so an administrator sees why they are writing)' }) workerVerificationStatus!: string | null;
  @ApiProperty({ nullable: true, description: 'For workers: the worker profile id (opens their application)' }) workerId!: string | null;
  @ApiProperty({ nullable: true }) lastMessage!: string | null;
  @ApiProperty({ enum: Role }) lastSenderRole!: Role;
  @ApiProperty() lastMessageAt!: string;
  @ApiProperty() messageCount!: number;
}

export class PagedSupportThreadsDto {
  @ApiProperty({ type: [AdminSupportThreadDto] }) items!: AdminSupportThreadDto[];
  @ApiProperty({ type: PageMetaDto }) meta!: PageMetaDto;
}

export class AdminSupportThreadDetailDto extends AdminSupportThreadDto {
  @ApiProperty({ type: [SupportMessageDto] }) messages!: SupportMessageDto[];
}
