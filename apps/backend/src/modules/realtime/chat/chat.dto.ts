import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import { IsIn, IsInt, IsOptional, IsString, IsUUID, Matches, Max, MaxLength, Min } from 'class-validator';

/** Chosen by the app for each message and reused when it retries, so a retry can never create a second message. */
export const CLIENT_MESSAGE_ID_RE = /^[A-Za-z0-9_-]{8,64}$/;

export class SendMessageDto {
  @ApiProperty({ description: 'A unique id generated by the app per message (8-64 chars: letters, digits, _ -). Resend the SAME id when retrying.' })
  @IsString()
  @Matches(CLIENT_MESSAGE_ID_RE)
  clientMessageId!: string;

  @ApiProperty({ description: 'Plain text, 1-2000 characters. No files or markup are interpreted.' })
  @IsString()
  @MaxLength(8000) // hard bound before the real (character-count) rule in the service
  body!: string;
}

export class SocketSendMessageDto extends SendMessageDto {
  @ApiProperty({ format: 'uuid' })
  @IsUUID()
  bookingId!: string;
}

export class ReceiptDto {
  @ApiProperty({ enum: ['DELIVERED', 'READ'] })
  @IsIn(['DELIVERED', 'READ'])
  kind!: 'DELIVERED' | 'READ';

  @ApiProperty({ description: 'Highest message seq this device has received (DELIVERED) or the user has seen (READ).' })
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(2147483647)
  upToSeq!: number;
}

export class SocketReceiptDto extends ReceiptDto {
  @ApiProperty({ format: 'uuid' })
  @IsUUID()
  bookingId!: string;
}

export class MessagesQueryDto {
  @ApiPropertyOptional({ description: 'Return messages with seq GREATER than this, oldest first (reconnect recovery).' })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(0)
  @Max(2147483647)
  afterSeq?: number;

  @ApiPropertyOptional({ description: 'Return messages with seq LESS than this, newest page first-to-last (scrolling back). Omit both for the latest page.' })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(2147483647)
  beforeSeq?: number;

  @ApiPropertyOptional({ default: 50, minimum: 1, maximum: 100 })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(200)
  limit: number = 50;
}

export class SocketSyncDto {
  @ApiProperty({ format: 'uuid' })
  @IsUUID()
  bookingId!: string;

  @ApiPropertyOptional()
  @IsOptional()
  @IsInt()
  @Min(0)
  @Max(2147483647)
  afterSeq?: number;

  @ApiPropertyOptional()
  @IsOptional()
  @IsInt()
  @Min(1)
  @Max(2147483647)
  beforeSeq?: number;

  @ApiPropertyOptional()
  @IsOptional()
  @IsInt()
  @Min(1)
  @Max(200)
  limit?: number;
}
